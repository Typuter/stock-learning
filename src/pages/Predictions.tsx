import { useAppStore } from '../store/appStore';
import type { Prediction } from '../types';

export function Predictions() {
  const { predictions } = useAppStore();

  const active = predictions.filter(p => p.wasAccurate === undefined);
  const scored = predictions.filter(p => p.wasAccurate !== undefined);

  // Group active predictions by symbol
  const grouped: Record<string, Prediction[]> = {};
  for (const pred of active) {
    if (!grouped[pred.symbol]) grouped[pred.symbol] = [];
    grouped[pred.symbol].push(pred);
  }

  return (
    <div className="page">
      <h2>Predictions</h2>

      <p style={{ fontSize: '0.8rem', color: '#888', marginBottom: '1.5rem' }}>
        Predictions generated by Kiro agent
      </p>

      {active.length === 0 ? (
        <div className="card">
          <p className="empty-state">No active predictions. Ask Kiro to generate a daily analysis.</p>
        </div>
      ) : (
        Object.entries(grouped).map(([symbol, preds]) => (
          <div key={symbol} style={{ marginBottom: '1.5rem' }}>
            <h3 style={{ color: '#89b4fa', marginBottom: '0.75rem' }}>{symbol}</h3>
            <div className="predictions-grid">
              {preds
                .sort((a, b) => {
                  const order = { '7d': 0, '14d': 1, '30d': 2 };
                  return order[a.timeframe] - order[b.timeframe];
                })
                .map((pred) => {
                  const signalColor = pred.signal === 'long' ? '#4ade80' : pred.signal === 'short' ? '#f38ba8' : '#888';
                  const signalBorder = pred.signal === 'long' ? '1px solid #4ade8040' : pred.signal === 'short' ? '1px solid #f38ba840' : '1px solid #2a2a4a';
                  const signalBg = pred.signal === 'long' ? '#4ade8008' : pred.signal === 'short' ? '#f38ba808' : 'transparent';
                  const signalLabel = pred.signal === 'long' ? '📈 LONG' : pred.signal === 'short' ? '📉 SHORT' : '⏸ HOLD';

                  return (
                    <div key={pred.id} className="card" style={{ border: signalBorder, background: signalBg }}>
                      <div className="prediction-header">
                        <span className="timeframe-badge">{pred.timeframe}</span>
                        <span style={{ fontWeight: 700, color: signalColor, fontSize: '0.85rem' }}>{signalLabel}</span>
                      </div>
                      <div className="prediction-range">
                        <span className="range-low">
                          {pred.predictedRangeLow > 0 ? '+' : ''}{pred.predictedRangeLow.toFixed(1)}%
                        </span>
                        <span className="range-separator">to</span>
                        <span className="range-high">
                          {pred.predictedRangeHigh > 0 ? '+' : ''}{pred.predictedRangeHigh.toFixed(1)}%
                        </span>
                      </div>
                      <div className="confidence">
                        Confidence: {pred.confidence}%
                      </div>
                      <ul className="reasoning-list">
                        {pred.reasoning.map((r, i) => <li key={i}>{r}</li>)}
                      </ul>
                      <p style={{ fontSize: '0.65rem', color: '#555', marginTop: '0.5rem' }}>
                        Generated: {new Date(pred.createdAt).toLocaleString()}
                      </p>
                    </div>
                  );
                })}
            </div>
          </div>
        ))
      )}

      {scored.length > 0 && (
        <div style={{ marginTop: '2rem' }}>
          <h2 style={{ marginBottom: '1rem' }}>Results</h2>
          <div className="card">
            <table className="data-table">
              <thead>
                <tr>
                  <th>Symbol</th>
                  <th>Timeframe</th>
                  <th>Predicted</th>
                  <th>Actual</th>
                  <th>Result</th>
                  <th>Date</th>
                </tr>
              </thead>
              <tbody>
                {scored.map(p => (
                  <tr key={p.id}>
                    <td className="ticker-symbol">{p.symbol}</td>
                    <td>{p.timeframe}</td>
                    <td>{p.predictedRangeLow > 0 ? '+' : ''}{p.predictedRangeLow.toFixed(1)}% to {p.predictedRangeHigh > 0 ? '+' : ''}{p.predictedRangeHigh.toFixed(1)}%</td>
                    <td className={p.actualResult !== undefined && p.actualResult >= 0 ? 'text-green' : 'text-red'}>
                      {p.actualResult !== undefined ? `${p.actualResult > 0 ? '+' : ''}${p.actualResult.toFixed(2)}%` : '—'}
                    </td>
                    <td>{p.wasAccurate ? '✅' : '❌'}</td>
                    <td style={{ fontSize: '0.75rem', color: '#666' }}>{new Date(p.createdAt).toLocaleDateString()}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      <p style={{ fontSize: '0.7rem', color: '#444', marginTop: '2rem', fontStyle: 'italic' }}>
        ⚠️ For educational purposes only. These predictions are AI-generated and not financial advice.
      </p>
    </div>
  );
}
